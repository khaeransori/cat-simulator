#!/usr/bin/env python3
"""Extract the Kenney Car Kit (CC0, kenney.nl) cars used by the approved low-poly mockup into
src/entities/carKit.ts. Vertex colours are baked from the kit colormap (flat palette cells), so
the game needs no GLB loader, no texture and no async loading.
Usage: python3 tools/carkit.py <dir with sedan.glb ... + carmap.png>"""
import json, struct, sys, os
from PIL import Image

d = sys.argv[1]
CARS = ['sedan', 'van', 'taxi', 'suv', 'truck', 'delivery']
im = Image.open(os.path.join(d, 'carmap.png')).convert('RGB')
W, H = im.size
pix = im.load()

def px(u, v):
    x = min(W - 1, max(0, int(((u % 1) + 1) % 1 * W)))
    y = min(H - 1, max(0, int(((v % 1) + 1) % 1 * H)))
    return pix[x, y], x, y

import base64, hashlib, array
out = {}
GEO = {}  # dedupe identical meshes (the 4 wheels of a car are the same mesh) across all cars
def pack(pos, nrm, col, cell, idx):
    # positions -> int16 at 1/4096 m (Kenney car units are < 4), normals -> int8, colour -> palette index
    pal = {}
    ci = []
    for i in range(len(col) // 3):
        k = (col[i*3], col[i*3+1], col[i*3+2], cell[i])
        if k not in pal: pal[k] = len(pal)
        ci.append(pal[k])
    assert len(pal) < 256
    P = array.array('h', [max(-32767, min(32767, round(v * 4096))) for v in pos])
    N = array.array('b', [max(-127, min(127, round(v * 127))) for v in nrm])
    C = array.array('B', ci)
    I = array.array('H', idx)
    b64 = lambda a: base64.b64encode(a.tobytes()).decode()
    return {'p': b64(P), 'n': b64(N), 'c': b64(C), 'i': b64(I), 'pal': [list(k) for k in pal]}
for name in CARS:
    b = open(os.path.join(d, name + '.glb'), 'rb').read()
    jl = struct.unpack_from('<I', b, 12)[0]
    j = json.loads(b[20:20 + jl])
    bin0 = 20 + jl + 8
    def acc(i):
        a = j['accessors'][i]; bv = j['bufferViews'][a['bufferView']]
        n = {'SCALAR': 1, 'VEC2': 2, 'VEC3': 3, 'VEC4': 4}[a['type']]
        fmt = {5126: 'f', 5123: 'H', 5125: 'I', 5121: 'B'}[a['componentType']]
        off = bin0 + bv.get('byteOffset', 0) + a.get('byteOffset', 0)
        return list(struct.unpack_from('<%d%s' % (a['count'] * n, fmt), b, off))
    meshes, nodes = {}, []
    for nd in j['nodes']:
        if 'mesh' not in nd: continue
        key = 'm%d' % nd['mesh']
        if key not in meshes:
            p = j['meshes'][nd['mesh']]['primitives'][0]
            pos = acc(p['attributes']['POSITION']); nrm = acc(p['attributes']['NORMAL'])
            uv = acc(p['attributes']['TEXCOORD_0']); idx = acc(p['indices'])
            col, cell = [], []
            for i in range(len(uv) // 2):
                (r, g, bb), x, y = px(uv[i * 2], uv[i * 2 + 1])
                col += [r, g, bb]
                cell.append(x // 32 + (y // 128) * 16)
            pk = pack(pos, nrm, col, cell, idx)
            h = hashlib.md5(json.dumps(pk, sort_keys=True).encode()).hexdigest()[:10]
            GEO.setdefault(h, pk)
            meshes[key] = h
        nodes.append({'name': nd['name'], 'geo': meshes[key], 't': nd.get('translation', [0, 0, 0]), 'r': nd.get('rotation', [0, 0, 0, 1]), 's': nd.get('scale', [1, 1, 1])})
    out[name] = nodes

src = ('// Kenney Car Kit (CC0, kenney.nl): %s as used by the approved low-poly mockup.\n'
       '// Generated by tools/carkit.py (vertex colours baked from the kit colormap). Do not edit.\n'
       '// geo: base64 int16 positions (/4096), int8 normals (/127), uint8 palette index, uint16 indices; pal = [r,g,b,cell]\n'
       'export const CAR_GEO: Record<string, { p: string; n: string; c: string; i: string; pal: number[][] }> = %s;\n'
       'export const CARKIT: Record<string, { name: string; geo: string; t: number[]; r: number[]; s: number[] }[]> = %s;\n') % (', '.join(CARS), json.dumps(GEO, separators=(',', ':')), json.dumps(out, separators=(',', ':')))
open('src/entities/carKit.ts', 'w').write(src)
print('carKit.ts %d KB' % (len(src) // 1024))
